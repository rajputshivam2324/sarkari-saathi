def build_facts(candidates: list[dict[str, Any]]) -> str:
    """Plain text of everything the model is allowed to state. Also used by the output guardrails."""
    chunks: list[str] = []
    for s in candidates:
        if s.get("facts"):
            chunks.append(str(s["facts"]))
        else:
            chunks.append(f"{s.get('name', '')}. {s.get('description', '')}. {s.get('description_hi', '')}")
    return "\n\n".join(chunks)


def build_context(
    *,
    mode: str,
    language: str,
    profile: dict[str, Any],
    candidates: list[dict[str, Any]],
    question_to_ask: str,
    turn: int,
    they_just_answered: str = "",
) -> str:
    cand_rows = []
    for i, s in enumerate(candidates, 1):
        row: dict[str, Any] = {"n": i, "name": s.get("name"), "category": s.get("category") or None}
        if s.get("facts"):
            row["FACTS"] = s["facts"]          # the official record, trimmed for speech
        elif s.get("description"):
            row["FACTS"] = f"{s.get('name')}. {s['description']}"
        else:
            row["note"] = "Only the name is known. Do not describe its benefits."
        cand_rows.append(row)

    ctx = {
        "reply_language": LANGUAGE_NAMES.get(language, LANGUAGE_NAMES["hi-IN"]),
        "turn_number": turn,
        "mode": mode,
        "mode_instruction": MODE_GUIDE[mode],
        "what_we_know_about_the_person": profile or "nothing yet",
        "question_to_ask": question_to_ask or "none",
        **({"they_just_answered": they_just_answered} if they_just_answered else {}),
        "CANDIDATES": cand_rows or "none",
        "FACTS_note": "Each candidate's FACTS come from the official myScheme.gov.in record. They are the only verified information.",
    }
    return (
        "CONTEXT (generated by the app for this turn; trusted):\n"
        + json.dumps(ctx, ensure_ascii=False, indent=1)
    )


def build_messages(
    *,
    context: str,
    history: list[dict[str, Any]],
    user_text: str,
    max_history: int = 8,
) -> list[dict[str, str]]:
    """System prompt + context, then the recent conversation, ending with the current user turn."""
    msgs: list[dict[str, str]] = [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "system", "content": context},
    ]
    recent = [m for m in history if m.get("role") in ("user", "assistant") and (m.get("text") or "").strip()]
    # The current user turn is passed separately; drop it if the caller already appended it.
    if recent and recent[-1].get("role") == "user" and recent[-1].get("text", "").strip() == user_text.strip():
        recent = recent[:-1]
    for m in recent[-max_history:]:
        msgs.append({"role": m["role"], "content": m["text"].strip()[:500]})
    msgs.append({"role": "user", "content": user_text.strip()[:800]})
    return msgs
