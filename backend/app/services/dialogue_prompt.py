"""The system prompt and the per-turn context that make the LLM sound like a person.

Split on purpose:
- SYSTEM_PROMPT is static (identical every turn, so the model server can cache the prefix): persona, voice,
  conversation craft, honesty limits, privacy, language, examples.
- build_context() is generated by the app every turn and is trusted: the verified scheme
  candidates, the person's profile, what kind of turn this is, and the single question the app
  allows. The model chooses the words; the app controls the substance.
"""

