def normalize_lang(code: str | None) -> str:
    if not code:
        return "hi-IN"
    c = code.strip().replace("_", "-")
    if c in TTS_LANGS:
        return c
    # map bare codes
    base = c.split("-")[0].lower()
    mapping = {
        "hi": "hi-IN",
        "en": "en-IN",
        "ta": "ta-IN",
        "te": "te-IN",
        "kn": "kn-IN",
        "ml": "ml-IN",
        "mr": "mr-IN",
        "pa": "pa-IN",
        "bn": "bn-IN",
        "gu": "gu-IN",
    }
    return mapping.get(base, "hi-IN")


def greeting(lang: str | None = None) -> str:
    return GREETINGS[normalize_lang(lang)]


def follow_need(lang: str | None = None) -> str:
    return FOLLOW_NEED[normalize_lang(lang)]


def match_reply(schemes: list[dict], lang: str | None = None) -> str:
    lang = normalize_lang(lang)
    if not schemes:
        return NO_MATCH[lang]
    parts = []
    for i, s in enumerate(schemes[:3], 1):
        parts.append(f"{i}. {s.get('name') or s.get('name_hi') or 'Scheme'}")
    return f"{MATCH_PREFIX[lang]} {' '.join(parts)} {MATCH_SUFFIX[lang]}"
